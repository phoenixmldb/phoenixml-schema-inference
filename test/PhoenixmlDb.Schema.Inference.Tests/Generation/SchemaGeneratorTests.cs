using PhoenixmlDb.Schema.Inference.Generation;
using Xunit;

namespace PhoenixmlDb.Schema.Inference.Tests.Generation;

public class SchemaGeneratorTests
{
    [Fact]
    public void FromJsonProducesXmlAndXsdAndSummary()
    {
        var json = """{ "order": { "id": "X", "total": 1.5 } }""";

        var result = SchemaGenerator.FromJson(json, "doc");

        Assert.NotEmpty(result.Xsd);
        Assert.NotEmpty(result.Xml);
        Assert.NotNull(result.Summary);
        Assert.True(result.Summary!.DocumentsObserved >= 1);
    }

    [Fact]
    public void FromXmlObservesAndReturnsXsd()
    {
        var xml = "<order><id>X</id><total>1.5</total></order>";

        var result = SchemaGenerator.FromXml(xml);

        Assert.Contains("name=\"order\"", result.Xsd);
        Assert.Contains("name=\"id\"", result.Xsd);
    }

    [Fact]
    public void FromFileThrowsOnEdiExtension()
    {
        var tmp = Path.GetTempFileName();
        var ediPath = tmp + ".edi";
        File.Move(tmp, ediPath);
        File.WriteAllText(ediPath, "ISA*00*...");
        try
        {
            Assert.Throws<NotSupportedException>(() => SchemaGenerator.FromFile(ediPath));
        }
        finally
        {
            File.Delete(ediPath);
        }
    }

    [Fact]
    public void InfersTypesFromJson()
    {
        var json = """
            {
              "order": {
                "id": "ORD-001",
                "total": 1500.00,
                "quantity": 10,
                "date": "2026-04-17",
                "active": true
              }
            }
            """;

        var result = SchemaGenerator.FromJson(json, "order-doc");

        Assert.NotEmpty(result.Xsd);
        Assert.Contains("xs:string", result.Xsd);    // id
        Assert.Contains("xs:decimal", result.Xsd);   // total
        Assert.Contains("xs:integer", result.Xsd);    // quantity
        Assert.Contains("xs:date", result.Xsd);       // date
        Assert.Contains("xs:boolean", result.Xsd);    // active

        Assert.NotNull(result.Summary);
        var elements = result.Summary!.Elements;
        Assert.Contains(elements, e => e.Name == "total" && e.InferredType == "Decimal");
        Assert.Contains(elements, e => e.Name == "date" && e.InferredType == "Date");
        Assert.Contains(elements, e => e.Name == "active" && e.InferredType == "Boolean");
    }

    [Fact]
    public void DetectsArraysFromJson()
    {
        var json = """
            {
              "items": [
                { "name": "Widget", "price": 9.99 },
                { "name": "Gadget", "price": 19.99 }
              ]
            }
            """;

        var result = SchemaGenerator.FromJson(json, "catalog");

        Assert.Contains("maxOccurs=\"unbounded\"", result.Xsd);
        Assert.NotNull(result.Summary);
        Assert.Contains(result.Summary!.Elements, e => e.Name == "items" && e.IsArray);
    }

    [Fact]
    public void InfersTypesFromCsv()
    {
        var csv = "id,amount,date,active\nORD-001,99.50,2026-01-01,true\nORD-002,150,2026-01-02,false";

        var result = SchemaGenerator.FromCsv(csv, "orders", "order");

        Assert.NotNull(result.Summary);
        var elements = result.Summary!.Elements;
        Assert.Contains(elements, e => e.Name == "amount" && e.InferredType == "Decimal");
        Assert.Contains(elements, e => e.Name == "date" && e.InferredType == "Date");
        Assert.Contains(elements, e => e.Name == "active" && e.InferredType == "Boolean");
    }

    [Fact]
    public void GeneratesValidXsd()
    {
        var json = """{"item": {"name": "Widget", "price": 9.99}}""";
        var result = SchemaGenerator.FromJson(json, "doc");

        // Should parse as valid XML
        var doc = System.Xml.Linq.XDocument.Parse(result.Xsd);
        Assert.Equal("schema", doc.Root!.Name.LocalName);
    }

    [Fact]
    public void IncludesSampleValuesInAnnotations()
    {
        var json = """{"order": {"customer": "Acme Corp"}}""";
        var result = SchemaGenerator.FromJson(json, "doc");

        Assert.Contains("Acme Corp", result.Xsd);
    }

    [Fact]
    public void IncludesGenerationMetadata()
    {
        var json = """{"x": 1}""";
        var result = SchemaGenerator.FromJson(json, "doc");

        Assert.Contains("Auto-generated by PhoenixmlDb.Schema.Inference", result.Xsd);
        Assert.Contains("Refine this schema", result.Xsd);
    }

    [Fact]
    public void AutoDetectsFormatFromExtension()
    {
        var jsonFile = Path.GetTempFileName() + ".json";
        File.WriteAllText(jsonFile, """{"test": {"value": 42}}""");

        try
        {
            var result = SchemaGenerator.FromFile(jsonFile);
            Assert.Contains("xs:integer", result.Xsd);
            Assert.Contains("Generated from JSON", result.Source);
        }
        finally
        {
            File.Delete(jsonFile);
        }
    }
}
