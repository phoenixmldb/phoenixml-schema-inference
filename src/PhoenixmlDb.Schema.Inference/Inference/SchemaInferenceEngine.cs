using System.Xml.Linq;

namespace PhoenixmlDb.Schema.Inference.Inference;

/// <summary>
/// Infers an XSD schema from one or more XML documents.
///
/// The generated schema starts loose — all elements optional, types inferred
/// from observed values. As more documents are observed, the schema becomes
/// more accurate: elements seen in every document become required, numeric
/// values produce xs:decimal types, dates produce xs:date, etc.
///
/// This is the "schema-on-read with progressive typing" pattern:
///   Day 1:  Drop a JSON file → XML + draft schema generated
///   Day 2:  Refine schema (make orderId required, total a decimal)
///   Day 7:  Add validation step → catches bad data early
///   Day 30: Schema is production-grade, shaped by real traffic
/// </summary>
public sealed class SchemaInferenceEngine
{
    private static readonly XNamespace Xs = "http://www.w3.org/2001/XMLSchema";

    private readonly Dictionary<string, InferredElement> _elements = new();
    private int _documentCount;

    /// <summary>
    /// Observes an XML document and updates the inferred schema.
    /// Call this multiple times with different documents to build a more
    /// accurate schema from real traffic patterns.
    /// </summary>
    public void Observe(string xml)
    {
        var doc = XDocument.Parse(xml);
        if (doc.Root is null) return;

        _documentCount++;
        ObserveElement(doc.Root, "");
    }

    /// <summary>
    /// Generates an XSD schema from all observed documents.
    /// </summary>
    public string GenerateXsd(string? targetNamespace = null)
    {
        var schema = new XElement(Xs + "schema",
            new XAttribute(XNamespace.Xmlns + "xs", Xs.NamespaceName));

        if (targetNamespace is not null)
        {
            schema.Add(new XAttribute("targetNamespace", targetNamespace));
            schema.Add(new XAttribute(XNamespace.Xmlns + "tns", targetNamespace));
            schema.Add(new XAttribute("elementFormDefault", "qualified"));
        }

        // Add annotation with generation metadata
        schema.Add(new XElement(Xs + "annotation",
            new XElement(Xs + "documentation",
                $"Auto-generated by PhoenixmlDb.Schema.Inference from {_documentCount} document(s). " +
                "Refine this schema to add constraints: make elements required, " +
                "restrict enumerations, tighten types.")));

        // Find the root element
        var root = _elements.Values.FirstOrDefault(e => e.Path.Length == 0);
        if (root is null) return schema.ToString();

        // Generate root element with inline complex type
        schema.Add(GenerateElementDeclaration(root, isRoot: true));

        return schema.ToString();
    }

    /// <summary>
    /// Generates a summary of what was observed — useful for CLI output.
    /// </summary>
    public SchemaInferenceSummary GetSummary()
    {
        return new SchemaInferenceSummary
        {
            DocumentsObserved = _documentCount,
            Elements = _elements.Values.Select(e => new InferredElementSummary
            {
                Path = e.FullPath,
                Name = e.Name,
                InferredType = e.InferredType.ToString(),
                IsRequired = e.OccurrenceCount == _documentCount,
                OccurrenceRate = _documentCount > 0
                    ? (double)e.OccurrenceCount / _documentCount
                    : 0,
                IsArray = e.MaxOccurrences > 1,
                HasAttributes = e.Attributes.Count > 0,
                SampleValues = e.SampleValues.Take(3).ToList()
            }).OrderBy(e => e.Path).ToList()
        };
    }

    private void ObserveElement(XElement element, string parentPath)
    {
        var path = parentPath.Length > 0 ? $"{parentPath}/{element.Name.LocalName}" : "";
        var key = path.Length > 0 ? path : element.Name.LocalName;

        if (!_elements.TryGetValue(key, out var inferred))
        {
            inferred = new InferredElement
            {
                Name = element.Name.LocalName,
                Path = parentPath,
                Namespace = element.Name.NamespaceName
            };
            _elements[key] = inferred;
        }

        inferred.OccurrenceCount++;

        // Observe attributes
        foreach (var attr in element.Attributes().Where(a => !a.IsNamespaceDeclaration))
        {
            if (!inferred.Attributes.TryGetValue(attr.Name.LocalName, out var inferredAttr))
            {
                inferredAttr = new InferredAttribute { Name = attr.Name.LocalName };
                inferred.Attributes[attr.Name.LocalName] = inferredAttr;
            }
            inferredAttr.OccurrenceCount++;
            inferredAttr.InferredType = RefineType(inferredAttr.InferredType, attr.Value);
            AddSample(inferredAttr.SampleValues, attr.Value);
        }

        // Observe children
        var childElements = element.Elements().ToList();
        if (childElements.Count > 0)
        {
            inferred.InferredType = XsdType.Complex;

            // Track child element names and their occurrence counts in this document
            var childCounts = childElements
                .GroupBy(c => c.Name.LocalName)
                .ToDictionary(g => g.Key, g => g.Count());

            foreach (var childGroup in childElements.GroupBy(c => c.Name.LocalName))
            {
                var childPath = path.Length > 0 ? path : element.Name.LocalName;

                // Track max occurrences for array detection
                var childKey = $"{childPath}/{childGroup.Key}";
                if (_elements.TryGetValue(childKey, out var childInferred))
                {
                    childInferred.MaxOccurrences = Math.Max(
                        childInferred.MaxOccurrences, childGroup.Count());
                }

                foreach (var child in childGroup)
                {
                    ObserveElement(child, childPath);
                }
            }

            // Track which children are present (for required/optional detection)
            foreach (var (childName, count) in childCounts)
            {
                var childKey = $"{(path.Length > 0 ? path : element.Name.LocalName)}/{childName}";
                if (_elements.TryGetValue(childKey, out var ci))
                {
                    ci.MaxOccurrences = Math.Max(ci.MaxOccurrences, count);
                }
            }
        }
        else
        {
            // Leaf element — infer type from text content
            var text = element.Value.Trim();
            if (text.Length > 0)
            {
                inferred.InferredType = RefineType(inferred.InferredType, text);
                AddSample(inferred.SampleValues, text);
            }
        }
    }

    private XElement GenerateElementDeclaration(InferredElement element, bool isRoot = false)
    {
        var el = new XElement(Xs + "element",
            new XAttribute("name", element.Name));

        if (!isRoot)
        {
            el.Add(new XAttribute("minOccurs", "0"));
            if (element.MaxOccurrences > 1)
                el.Add(new XAttribute("maxOccurs", "unbounded"));
        }

        // Find children
        var childPath = element.Path.Length > 0
            ? $"{element.Path}/{element.Name}"
            : element.Name;

        var children = _elements.Values
            .Where(e => e.Path == childPath)
            .OrderBy(e => e.Name)
            .ToList();

        if (children.Count > 0 || element.Attributes.Count > 0)
        {
            // Complex type
            var complexType = new XElement(Xs + "complexType");

            if (children.Count > 0)
            {
                var sequence = new XElement(Xs + "sequence");
                foreach (var child in children)
                {
                    sequence.Add(GenerateElementDeclaration(child));
                }
                complexType.Add(sequence);
            }

            foreach (var attr in element.Attributes.Values.OrderBy(a => a.Name))
            {
                complexType.Add(new XElement(Xs + "attribute",
                    new XAttribute("name", attr.Name),
                    new XAttribute("type", MapXsdType(attr.InferredType)),
                    new XAttribute("use", attr.OccurrenceCount == _documentCount
                        ? "required" : "optional")));
            }

            el.Add(complexType);
        }
        else
        {
            // Simple type
            el.Add(new XAttribute("type", MapXsdType(element.InferredType)));
        }

        // Add annotation with sample values
        if (element.SampleValues.Count > 0 && children.Count == 0)
        {
            el.AddFirst(new XElement(Xs + "annotation",
                new XElement(Xs + "documentation",
                    $"Samples: {string.Join(", ", element.SampleValues.Take(3))}")));
        }

        return el;
    }

    internal static XsdType RefineType(XsdType current, string value)
    {
        var observed = InferTypeFromValue(value);

        if (current == XsdType.Unknown)
            return observed;

        // If types disagree, widen to string (the universal fallback)
        if (current != observed)
        {
            // Numeric widening: integer → decimal
            if ((current == XsdType.Integer && observed == XsdType.Decimal) ||
                (current == XsdType.Decimal && observed == XsdType.Integer))
                return XsdType.Decimal;

            return XsdType.String;
        }

        return current;
    }

    private static XsdType InferTypeFromValue(string value)
    {
        if (string.IsNullOrEmpty(value)) return XsdType.String;
        if (value.Equals("true", StringComparison.OrdinalIgnoreCase) ||
            value.Equals("false", StringComparison.OrdinalIgnoreCase)) return XsdType.Boolean;
        if (long.TryParse(value, out _)) return XsdType.Integer;
        if (decimal.TryParse(value, out _)) return XsdType.Decimal;
        if (DateOnly.TryParse(value, out _)) return XsdType.Date;
        if (DateTimeOffset.TryParse(value, out _)) return XsdType.DateTime;
        return XsdType.String;
    }

    private static string MapXsdType(XsdType type) => type switch
    {
        XsdType.String => "xs:string",
        XsdType.Integer => "xs:integer",
        XsdType.Decimal => "xs:decimal",
        XsdType.Boolean => "xs:boolean",
        XsdType.Date => "xs:date",
        XsdType.DateTime => "xs:dateTime",
        _ => "xs:string"
    };

    private static void AddSample(List<string> samples, string value)
    {
        if (samples.Count < 5 && !samples.Contains(value))
            samples.Add(value);
    }

    private sealed class InferredElement
    {
        public required string Name { get; init; }
        public required string Path { get; init; }
        public string? Namespace { get; init; }
        public XsdType InferredType { get; set; } = XsdType.Unknown;
        public int OccurrenceCount { get; set; }
        public int MaxOccurrences { get; set; } = 1;
        public Dictionary<string, InferredAttribute> Attributes { get; } = new();
        public List<string> SampleValues { get; } = [];

        public string FullPath => Path.Length > 0 ? $"{Path}/{Name}" : Name;
    }

    private sealed class InferredAttribute
    {
        public required string Name { get; init; }
        public XsdType InferredType { get; set; } = XsdType.Unknown;
        public int OccurrenceCount { get; set; }
        public List<string> SampleValues { get; } = [];
    }
}

public enum XsdType
{
    Unknown,
    String,
    Integer,
    Decimal,
    Boolean,
    Date,
    DateTime,
    Complex
}
